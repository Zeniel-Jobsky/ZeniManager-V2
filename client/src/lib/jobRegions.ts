export const JOB_REGION_CHILD_COUNT = JOB_REGION_PROVINCES.reduce((total, item) => total + item.children.length, 0);

export function findJobRegionOption(code: string): JobRegionOption | undefined {
  if (code === JOB_REGION_ANY.code) return JOB_REGION_ANY;
  for (const item of JOB_REGION_PROVINCES) {
    if (item.code === code) return item;
    const child = item.children.find(candidate => candidate.code === code);
    if (child) return child;
  }
  return undefined;
}
