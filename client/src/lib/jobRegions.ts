import type { JobRegionFilter } from './jobRecommendations';

export interface JobRegionOption extends JobRegionFilter {
  shortLabel: string;
  provinceCode: string;
}

export interface JobRegionProvince extends JobRegionOption {
  children: JobRegionOption[];
}

type ChildDefinition = readonly [code: string, label: string];

function province(code: string, label: string, children: readonly ChildDefinition[]): JobRegionProvince {
  return {
    code,
    label,
    shortLabel: label,
    provinceCode: code,
    children: children.map(([childCode, childLabel]) => ({
      code: `${code}/${childCode}`,
      label: `${label} ${childLabel}`,
      shortLabel: childLabel,
      provinceCode: code,
    })),
  };
}

